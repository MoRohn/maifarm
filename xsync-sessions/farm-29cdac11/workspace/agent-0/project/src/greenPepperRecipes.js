// Helper functions for recipe management
export function getRecipesByCategory(category) {
    return Object.entries(greenPepperRecipes)
        .filter(([_, recipe]) => recipe.category === category)
        .map(([key, recipe]) => ({ id: key, ...recipe }));
}

export function getFeaturedRecipes() {
    return Object.entries(greenPepperRecipes)
        .filter(([_, recipe]) => recipe.featured)
        .map(([key, recipe]) => ({ id: key, ...recipe }));
}

export function getQuickRecipes(maxMinutes = 30) {
    return Object.entries(greenPepperRecipes)
        .filter(([_, recipe]) => (recipe.prepTime + recipe.cookTime) <= maxMinutes)
        .map(([key, recipe]) => ({ id: key, ...recipe }));
}

export function searchRecipes(searchTerm) {
    const term = searchTerm.toLowerCase();
    return Object.entries(greenPepperRecipes)
        .filter(([_, recipe]) => {
            return recipe.name.toLowerCase().includes(term) ||
                   recipe.category.toLowerCase().includes(term) ||
                   recipe.ingredients.some(ing => ing.toLowerCase().includes(term));
        })
        .map(([key, recipe]) => ({ id: key, ...recipe }));
}

export function getRecipeById(id) {
    return greenPepperRecipes[id] || null;
}

export function getAllCategories() {
    const categories = new Set();
    Object.values(greenPepperRecipes).forEach(recipe => {
        categories.add(recipe.category);
    });
    return Array.from(categories).sort();
}
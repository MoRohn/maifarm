// Function to get recipes by ingredient
export function getRecipesByIngredient(ingredient) {
    const matchingRecipes = [];
    
    for (const [key, recipe] of Object.entries(recipes)) {
        const hasIngredient = recipe.ingredients.some(ing => 
            ing.toLowerCase().includes(ingredient.toLowerCase())
        );
        
        if (hasIngredient) {
            matchingRecipes.push({ key, ...recipe });
        }
    }
    
    return matchingRecipes;
}

// Function to get recipes by cooking time
export function getQuickRecipes(maxMinutes = 30) {
    const quickRecipes = [];
    
    for (const [key, recipe] of Object.entries(recipes)) {
        if (recipe.prepTime + recipe.cookTime <= maxMinutes) {
            quickRecipes.push({ key, ...recipe });
        }
    }
    
    return quickRecipes;
}

// Function to calculate total nutrition for a recipe
export function calculateRecipeNutrition(recipeKey, servings = 1) {
    const recipe = recipes[recipeKey];
    if (!recipe) return null;
    
    const portionMultiplier = servings / recipe.servings;
    const nutrition = { ...recipe.nutritionPer100g };
    
    // Adjust for portion size (assuming 100g per serving as base)
    Object.keys(nutrition).forEach(key => {
        nutrition[key] = Math.round(nutrition[key] * portionMultiplier * 100) / 100;
    });
    
    return nutrition;
}